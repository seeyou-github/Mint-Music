import 'dart:io';

/// 网格列表（带封面的歌单 / 榜单 / 专辑 / 作者卡片）每页行数。
///
/// 每页条数 = 行数 × 当前列数，所以同一个行数在不同平台上差别很大：
/// Android 手机一屏只能放 3 列，一页 10 行只有 30 张封面，翻页太碎，
/// 因此按 30 行铺；桌面（Windows）窄边栏布局下能排到 5~7 列，一页 10 行
/// 已有 50+ 张，再放大到 30 行等于一页 150+ 张，单次渲染量和接口请求量都
/// 翻了 3 倍，所以桌面保持 10 行。
///
/// 其他平台（iOS / macOS / Linux）沿用桌面口径。
int get gridPageRows => Platform.isAndroid ? 30 : 10;
